export interface Trip {
  dep: number; // minutes since midnight
  arr: number;
  depStr: string;
  arrStr: string;
}

export function parseTime(str: string): number {
  const [h, m] = str.split(":").map(Number);
  return h * 60 + m;
}

export function isWeekendDate(date: Date): boolean {
  const d = date.getDay();
  return d === 0 || d === 6;
}

export function getTables(forceHoliday: boolean, date: Date) {
  const isWeekend = forceHoliday || isWeekendDate(date);
  return isWeekend
    ? { down: WE_DOWN, up: WE_UP, isWeekend: true }
    : { down: WD_DOWN, up: WD_UP, isWeekend: false };
}

export function getTrips(originIdx: number, destIdx: number, forceHoliday: boolean, date: Date): Trip[] {
  if (originIdx === destIdx) return [];
  const { down, up } = getTables(forceHoliday, date);
  const originArr = originIdx < destIdx ? down[originIdx] : up[originIdx];
  const destArr = originIdx < destIdx ? down[destIdx] : up[destIdx];
  const len = Math.min(originArr.length, destArr.length);
  const trips: Trip[] = [];
  for (let i = 0; i < len; i++) {
    trips.push({
      dep: parseTime(originArr[i]),
      arr: parseTime(destArr[i]),
      depStr: originArr[i],
      arrStr: destArr[i],
    });
  }
  return trips;
}

export function minutesLabel(mins: number): string {
  if (mins <= 0) return "Berlepas sekarang";
  if (mins < 60) return `${mins} min`;
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return m === 0 ? `${h} j` : `${h} j ${m} m`;
}
